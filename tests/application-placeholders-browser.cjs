// Application controls and field-scoped placeholders, with synthetic data only.
const assert = require("node:assert/strict"), { chromium } = require("playwright");
const { createPublicFoodHarness, routeSyntheticSdk } = require("./helpers/public-browser-site.cjs");
const { server, mock, extra, cleanup } = createPublicFoodHarness("application-placeholders");
(async () => {
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1160, height: 1000 } }), errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.addInitScript(() => { if (window === window.top) localStorage.setItem("rsvp-interface-language", "en"); });
    const publicationSeed = `window.__publicationWrites=[];
const publicationFrom=client.from;client.from=function(name){const query=publicationFrom.call(this,name);if(name==='event_settings')query.update=values=>({eq:async()=>{
window.__publicationWrites.push(structuredClone(values));
if(window.__holdPublication){await new Promise(resolve=>window.__releasePublication=resolve);window.__holdPublication=false;}
if(window.__failPublication){window.__failPublication=false;return {error:{message:'Synthetic publication failure'}};}
Object.assign(fixtures.event_settings[0],values);return {data:null,error:null};}});return query;};`;
    await routeSyntheticSdk(page, mock + "\n" + extra + "\n" + publicationSeed);
    const base = "http://127.0.0.1:" + server.address().port;
    await page.goto(base + "/admin/");
    await page.waitForFunction(() => document.querySelector("#inviteOverviewCounts .invite-stat-row"));
    await page.locator("#settingsToggle").click();
    const application = page.locator('[data-settings-panel="application"]');
    assert.equal(await application.isVisible(), true);
    assert.equal(await application.locator("#publicationBadge").textContent(), "Unpublished");
    assert.deepEqual(await application.locator("#publicationSummary dt").allTextContents(), ["Guest access", "Website", "Invitation delivery"]);
    assert.deepEqual(await application.locator("#publicationSummary dd").allTextContents(), ["Private preview only", "Online", "Available after publication"]);
    assert.equal(await application.locator(".application-guidance").evaluate(node => node.open), false);
    assert.equal(await application.locator(".application-completed-checks").evaluate(node => node.open), false);
    const pending = await application.locator("#launchChecklist li").count(), completed = await application.locator("#completedLaunchChecks li").count();
    assert.equal(pending + completed, 7, "all current launch facts represented once");
    assert.equal(await application.locator("#launchChecklistCount").textContent(), completed + " / 7");
    assert.equal(await application.locator("#launchChecklist .application-status-badge").count(), pending);
    assert.equal(await application.locator("#publishEventButton").isDisabled(), true, "publish starts behind acknowledgement");
    const publicationAlignment = await application.locator(".publication-actions").evaluate(actions => {
      const bounds = selector => actions.querySelector(selector).getBoundingClientRect();
      const publish = bounds("#publishEventButton"), check = bounds("#publishAck"), wording = bounds(".publish-ack span");
      return { order: publish.right <= check.left && check.right <= wording.left,
        aligned: Math.abs(check.top + check.bottom - wording.top - wording.bottom) < 2 };
    });
    assert.deepEqual(publicationAlignment, { order: true, aligned: true });
    await application.locator("#publishAck").check();
    assert.equal(await application.locator("#publishEventButton").isEnabled(), true);
    await application.locator("#publishAck").uncheck();
    assert.equal(await application.locator("#publishEventButton").isDisabled(), true);
    await application.locator("#publishAck").check();
    await application.locator("#publishEventButton").click();
    await application.locator(".inline-confirmation").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal(await page.evaluate(() => window.__publicationWrites.length), 0, "cancel does not publish");
    await application.locator("#publishEventButton").click();
    await application.locator("#publishAck").uncheck();
    await application.locator(".inline-confirmation [data-inline-confirm]").click();
    assert.equal(await page.evaluate(() => window.__publicationWrites.length), 0, "withdrawing acknowledgement while confirmation is open prevents publication");
    await application.locator("#publishAck").check();
    await page.evaluate(() => window.__failPublication = true);
    await application.locator("#publishEventButton").click();
    await application.locator(".inline-confirmation [data-inline-confirm]").click();
    await page.waitForFunction(() => window.__publicationWrites.length === 1 && !document.getElementById("publishEventButton").disabled);
    assert.match(await page.locator("#adminMessage").innerText(), /Synthetic publication failure/);
    assert.equal(await application.locator("#publishAck").isChecked(), true, "error retains acknowledgement for deliberate retry");
    await page.evaluate(() => window.__holdPublication = true);
    await application.locator("#publishEventButton").click();
    await application.locator(".inline-confirmation [data-inline-confirm]").click();
    await page.waitForFunction(() => typeof window.__releasePublication === "function");
    assert.equal(await application.locator("#publishEventButton").isDisabled(), true);
    assert.equal(await application.locator("#publishAck").isDisabled(), true, "pending publication cannot be re-enabled by acknowledgement");
    await page.evaluate(() => window.__releasePublication());
    await page.waitForFunction(() => document.getElementById("publicationBadge").textContent === "Published");
    assert.equal(await application.locator("#publishEventButton").isVisible(), false);
    assert.equal(await application.locator("#unpublishEventButton").isEnabled(), true);
    await application.locator("#unpublishEventButton").click();
    await application.locator(".inline-confirmation").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal(await page.evaluate(() => window.__publicationWrites.length), 2);
    await application.locator("#unpublishEventButton").click();
    await application.locator(".inline-confirmation [data-inline-confirm]").click();
    await page.waitForFunction(() => document.getElementById("publicationBadge").textContent === "Unpublished");
    assert.equal(await application.locator("#publishAck").isChecked(), false);
    assert.equal(await application.locator("#publishEventButton").isDisabled(), true);
    await page.evaluate(() => window.__accessPermissions.sections.settings = "view");
    await page.locator("#refreshButton").click();
    await page.waitForFunction(() => !document.getElementById("refreshButton").disabled);
    assert.equal(await application.locator("#publishAck").isDisabled(), true);
    await application.locator("#publishEventButton").evaluate(node => node.dispatchEvent(new MouseEvent("click", { bubbles: true })));
    assert.equal(await page.evaluate(() => window.__publicationWrites.length), 3, "view-only event handler rejects programmatic write");
    await page.evaluate(() => window.__accessPermissions.sections.settings = "edit");
    await page.locator("#refreshButton").click();
    await page.waitForFunction(() => !document.getElementById("refreshButton").disabled);
    const geometry = await application.evaluate(node => {
      const cards = [...node.querySelectorAll(":scope > section")].map(card => card.getBoundingClientRect());
      return { left: cards[0].left, right: cards[1].left, topDifference: Math.abs(cards[0].top - cards[1].top) };
    });
    assert.ok(geometry.right > geometry.left && geometry.topDifference < 2, "publication/checklist share wide row");
    await page.setViewportSize({ width: 390, height: 900 });
    assert.equal(await application.evaluate(node => {
      const cards = [...node.querySelectorAll(":scope > section")].map(card => card.getBoundingClientRect());
      return Math.abs(cards[0].left - cards[1].left) < 2 && cards[1].top >= cards[0].bottom;
    }), true, "application cards stack on phones");
    await page.locator('[data-settings-tab="placeholders"]').click();
    const reference = page.locator("#placeholderReference");
    assert.equal(await reference.locator("select").count(), 0);
    assert.doesNotMatch(await reference.innerText(), /Placeholder context/);
    assert.deepEqual(await reference.locator("[data-placeholder-category]").allTextContents(), ["All", "Event", "Household", "Venue", "Session", "Invitation salutation"]);
    await reference.getByRole("searchbox", { name: "Search placeholders" }).fill("deadline");
    assert.equal(await reference.locator(".placeholder-reference-row").count(), 4);
    await reference.getByRole("searchbox", { name: "Search placeholders" }).fill("");
    await reference.getByRole("tab", { name: "Household", exact: true }).click();
    const household = await reference.locator("code").allTextContents();
    assert.ok(household.includes("{household_name}") && !household.includes("{event_name}"));
    await reference.getByRole("tab", { name: "Household", exact: true }).press("ArrowRight");
    assert.equal(await reference.getByRole("tab", { name: "Venue", exact: true }).getAttribute("aria-selected"), "true");
    await reference.getByRole("searchbox", { name: "Search placeholders" }).fill("map");
    assert.deepEqual(await reference.locator("code").allTextContents(), ["{venue_map_link}"]);
    await page.evaluate(() => {
      const R = window.RSVP, form = R.dom("form"), label = R.dom("label", {}, "Synthetic field"), input = R.dom("textarea");
      form.id = "scopedPlaceholderFixture"; input.id = "scopedPlaceholderInput"; input.value = "Portion: "; input.setAttribute("aria-label", "Synthetic field");
      label.append(input); form.append(label); document.getElementById("placeholderReference").append(form);
      window.RSVP_PLACEHOLDER_HELP.attach(input, { R, T: window.RSVP_I18N.t, tokens: ["{item}"], kind: "shared" });
      input.addEventListener("input", () => window.__placeholderInsertEvents = (window.__placeholderInsertEvents || 0) + 1);
    });
    const fixture = page.locator("#scopedPlaceholderFixture");
    await fixture.locator(".placeholder-help-toggle").click();
    assert.equal(await fixture.locator("select").count(), 0);
    assert.deepEqual(await fixture.locator(".placeholder-help code").allTextContents(), ["{item}"], "field picker never adds unsupported tokens");
    await fixture.getByRole("searchbox", { name: "Search placeholders" }).fill("item");
    await fixture.getByRole("button", { name: "Insert {item}", exact: true }).click();
    assert.equal(await page.locator("#scopedPlaceholderInput").inputValue(), "Portion: {item}");
    assert.equal(await page.evaluate(() => window.__placeholderInsertEvents), 1, "native input lifecycle retained");
    await page.locator("#scopedPlaceholderInput").evaluate(node => node.readOnly = true);
    await fixture.getByRole("button", { name: "Insert {item}", exact: true }).click();
    assert.equal(await page.locator("#scopedPlaceholderInput").inputValue(), "Portion: {item}");
    await fixture.getByRole("button", { name: "Close", exact: true }).click();
    assert.equal(await fixture.locator(".placeholder-help").isVisible(), false);
    assert.equal(await page.evaluate(() => fixtures.event_settings[0].is_published), false, "no populated publication operation exercised");
    assert.deepEqual(errors, []);
    console.log("PASS Application: real checklist counts, pending/completed grouping, acknowledgement guard and responsive cards; placeholder category/search/keyboard and exact field-supported insertion.");
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); cleanup(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
